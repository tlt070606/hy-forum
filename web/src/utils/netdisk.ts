/**
 * 网盘分享内容的处理（前端侧）。
 *
 * ==========================================================================
 * 为什么需要它：真实用户粘贴的是**一整段分享文案**，不是一条干净的 URL
 * ==========================================================================
 * 实测（2026-09-18）：
 * - 粘贴夸克的整段文案 → 后端 `HTTP 400 {"code":400,"message":"diskUrl 必须是 http/https 链接"}`
 * - 只贴 URL → `HTTP 200`
 *
 * 也就是说**后端要求 diskUrl 是链接**，而用户从网盘 App 复制出来的东西长这样：
 *
 * ```
 * 我用夸克网盘给你分享了「26网课大全」，点击链接或复制整段内容，打开「夸克APP」即可获取。
 * /~1a2b3c4d~:/ 链接：https://pan.quark.cn/s/1a2b3c4d5e6f
 * ```
 *
 * 需求方（2026-09-18）明确要求：**不要校验，直接复制粘贴就能发**。
 * 所以前端在提交前把**其中那条链接抽出来**，而不是把整段文案原样发出去 ——
 * 整段文案既过不了后端校验，也不是一个可用的"分享链接"（详情页要拿它给用户点开）。
 *
 * ⚠️ 这是**输入归一化**，不是"校验"：用户粘什么都被接受，只是最终存下来的是链接本身。
 *    而且界面会**明确显示"将保存为：…"**，不做静默改写。
 *
 * ⚠️ 为什么不改成"后端也接受整段文案"：那是契约与后端校验的事（`server/**` 不归前端），
 *    已作为观察登记进报告。前端这一层无论后端改不改都该有 —— 存进去的东西得是能用的链接。
 */

/**
 * 从任意文本里抽出第一条 `http(s)` 链接。
 *
 * 边界处理：
 * - 结束字符排除**中英文标点与引号括号**（分享文案里链接后面常紧跟「，」「。」「」」等，
 *   不排除就会把标点一起抽进来，存成一个点不开的地址）；
 * - 末尾再兜一次去标点：有些文案的链接后面是换行/空格后接标点，正则可能多吃一个字符。
 *
 * @returns 抽到的链接；没有则返回空串（调用方据此提示用户）
 */
export function extractUrl(raw: string | null | undefined): string {
  const text = (raw ?? '').trim()
  if (!text) return ''

  // 允许链接里出现常见的 URL 字符；遇到空白或中英文标点/括号就停
  const matched = /https?:\/\/[^\s，。、；：！？""''（）()【】\[\]<>「」『』]+/i.exec(text)
  if (!matched) return ''

  // 去掉可能粘在末尾的标点（`.` `,` `)` 之类在链接里合法，但收尾处通常是标点）
  return matched[0].replace(/[.,;:!?，。；：！？、）)】」』"'`]+$/, '')
}

/**
 * 该网盘类型**有没有"提取码"这个概念**。
 *
 * 依据（需求方 2026-09-18 的原话：「没有什么提取码，人家现在都内嵌好了的，
 * 提取码都放好了，他在那个链接里面都弄好了」+《技术方案》§5.5 的表格）：
 * - **阿里云盘、夸克网盘**：根本没有提取码机制（链接即是全部）
 * - 百度网盘：可选带 `?pwd=`，**后端会从链接里拆出来**（§5.5 第 2 条）
 * - 天翼、迅雷等：有独立访问码
 *
 * 所以对前两种**不显示提取码输入框**，避免给用户"我还得填点什么"的错觉。
 *
 * @param diskType 契约 `PostCreateRequest.diskType`：1百度 2阿里 3夸克 4天翼 5迅雷 6其他
 */
export function diskTypeHasNoCode(diskType: number | null | undefined): boolean {
  // 2 = 阿里云盘，3 = 夸克网盘
  return diskType === 2 || diskType === 3
}
