-- =============================================================
-- Hy论坛 初始化数据  seed.sql
-- 对应里程碑：PLAN.md §4 的 M0
-- 前置：先执行 schema.sql
-- 设计原则（很重要）：
--   1. **本脚本只负责"首次基线"，绝不覆盖运行期数据。**
--      全表使用 INSERT IGNORE：已存在则跳过。
--      原因：版块、注册模式（sys_config）、敏感词、管理员密码都属于**运行期状态**，
--      由管理后台维护。若用 ON DUPLICATE KEY UPDATE，重跑 seed 会把管理员
--      改过的 register_mode 或改过的密码**静默重置**，这是生产事故级的隐患。
--   2. 因此本脚本可**重复执行**（对应验收项 M0_seed_runs_twice_safely）。
--   3. 后续增删版块/敏感词一律走管理后台接口，不再改本文件。
-- =============================================================

USE hy_forum;

-- ---------------------------------------------------------------
-- 1. 管理员账号
--    ⚠️ password_hash 是占位符，**登录必然失败**（fail-closed，不会误开一个弱口令后门）。
--    替换方式（二选一）：
--      a) M1 完成后，用后端的 BCryptPasswordEncoder 生成 strength=10 的哈希；
--      b) 用任意可信的 BCrypt 工具生成（$2a$10$...，前缀必须是 $2a$ 或 $2b$）。
--    生成后替换下面的字符串，并在首次登录后立即改密。
-- ---------------------------------------------------------------
